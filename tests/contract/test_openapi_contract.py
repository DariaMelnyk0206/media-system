REQUIRED_SCHEMAS = [
    "MediaItem",
    "Topic",
    "TopicSummary",
    "MediaItemRef",
    "TopicRef",
    "CreateMediaItemRequest",
    "UpdateMediaItemRequest",
    "CreateTopicRequest",
    "UpdateTopicRequest",
    "SearchResultItem",
    "ErrorResponse",
]


class TestComponentSchemas:
    """Required component schemas are present and correctly structured."""

    @pytest.mark.parametrize("schema_name", REQUIRED_SCHEMAS)
    def test_schema_present(self, schema_name: str, live_schemas: dict) -> None:
        assert schema_name in live_schemas, (
            f"Component schema {schema_name!r} missing from live /openapi.json"
        )

    def test_error_response_properties(self, live_schemas: dict) -> None:
        """ErrorResponse exposes all three contract fields as properties."""
        er = live_schemas.get("ErrorResponse", {})
        props = set(er.get("properties", {}).keys())
        assert {"error", "field", "message"} <= props, (
            f"ErrorResponse properties: {sorted(props)}"
        )

    def test_error_response_required(self, live_schemas: dict) -> None:
        """'error' and 'message' are required in ErrorResponse.

        'field' is nullable with a default of null, so Pydantic omits it from
        required[] — that is intentional and correct per the contract.
        """
        er = live_schemas.get("ErrorResponse", {})
        required = set(er.get("required", []))
        assert {"error", "message"} <= required, (
            f"ErrorResponse required fields: {sorted(required)}"
        )

    def test_media_item_properties(self, live_schemas: dict) -> None:
        """MediaItem exposes all 7 contract fields as properties."""
        mi = live_schemas.get("MediaItem", {})
        props = set(mi.get("properties", {}).keys())
        expected = {"id", "name", "type", "status", "notes", "rating", "topics"}
        assert expected <= props, f"MediaItem properties: {sorted(props)}"

    def test_topic_properties(self, live_schemas: dict) -> None:
        """Topic exposes id, name, media_items as properties."""
        t = live_schemas.get("Topic", {})
        props = set(t.get("properties", {}).keys())
        assert {"id", "name", "media_items"} <= props, f"Topic properties: {sorted(props)}"

    def test_search_result_item_properties(self, live_schemas: dict) -> None:
        """SearchResultItem exposes kind, id, name as properties."""
        sri = live_schemas.get("SearchResultItem", {})
        props = set(sri.get("properties", {}).keys())
        assert {"kind", "id", "name"} <= props, f"SearchResultItem properties: {sorted(props)}"


